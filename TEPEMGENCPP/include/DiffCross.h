// ---------------------------------------------------------------------------
// The public entry point
// ---------------------------------------------------------------------------

template <typename T>
struct DiffCrossResult {
  T dsigma;    ///< kbarn/MeV^4/(Z*alpha)^4, as the Fortran returns
  bool ok;     ///< false if an unphysical branch was taken (Fortran: setzero)
  T survival;  ///< |NT| / max|Ni| at the moment of summation -- see below
};

/// Evaluate the differential cross section at one kinematic point.
///
/// Deliberately does NOT reproduce the Fortran's final guard
///
///     IF((setzero.EQ.1).OR.(dsigma.LT.0)) THEN dsigma=0; badcount=badcount+1
///
/// That test is unsound and replacing it is a large part of the point of this
/// port. Cancellation produces garbage of either sign, so testing the sign
/// catches only half of it: measured over 100k sampled points it fires on
/// 0.019% while 0.25% are more than 10% wrong -- about one bad point in
/// thirteen. Worse, the half it misses is the positive half, which flows on
/// into the weight and the variance estimate.
///
/// `survival` is reported instead. It is |NT| / max|Ni|: the fraction of the
/// summed amplitude that was not destroyed by cancellation, taken before the
/// normalisation factors are applied. Near the machine epsilon of T the result
/// carries no significant digits, and the caller should re-evaluate the point
/// in a wider type rather than discard it. See doc/02-findings.md section 3.
template <typename T>
DiffCrossResult<T> diffCross(const PhysParams<T>& phys, T ppvt, T yp, T pmvt,
                             T ym, T dphi)
{
  bool ok = true;
  T survival{};
  const T nt = diffCrossTerms(phys, ppvt, yp, pmvt, ym, dphi, ok, &survival);
  return {nt, ok, survival};
}

